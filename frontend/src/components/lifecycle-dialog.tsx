"use client";
import { useState, type FormEvent } from "react";
import type { LifecycleAction, Subscription } from "@/lib/types";
import { actionLabels } from "@/lib/lifecycle";
import { todayInIndia } from "@/lib/format";
import { useAuth } from "./auth-provider";
import { Button, Modal, Notice } from "./ui";

const explanations: Record<LifecycleAction, string> = {
  quotation:
    "Create a quotation from this draft. Its expiry is the selected business date plus the validity period.",
  confirm:
    "Accept the quotation and freeze the current commercial prices, tax rates, and plan terms. The quotation and selected catalog must be valid on the business date.",
  activate:
    "Start this confirmed agreement. The next invoice date will be its original start date, including when activation is delayed. No invoice is generated by this action.",
  pause:
    "Pause this Active agreement under its accepted plan terms. The start date and next invoice date remain unchanged. Billing rules for paused periods are still pending.",
  resume:
    "Clear the pause condition. This does not change the billing anchor or next invoice date.",
  renew:
    "Extend this Active agreement without changing its accepted prices or billing anchor. Choose an expiry after both its current expiry and the business date.",
  close:
    "Close this agreement permanently. Its next invoice date will be cleared. A closed subscription cannot resume or renew.",
};
export function LifecycleDialog({
  subscription,
  action,
  onClose,
  onSuccess,
}: {
  subscription: Subscription;
  action: LifecycleAction;
  onClose: () => void;
  onSuccess: (subscription: Subscription) => void;
}) {
  const { api } = useAuth();
  const [asOf, setAsOf] = useState(todayInIndia());
  const [validity, setValidity] = useState("30");
  const [expiry, setExpiry] = useState("");
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState("");
  async function submit(event: FormEvent) {
    event.preventDefault();
    setError("");
    if (
      action === "renew" &&
      expiry <=
        (subscription.expiry_date > asOf ? subscription.expiry_date : asOf)
    ) {
      setError(
        "New expiry must be later than the current expiry and business date.",
      );
      return;
    }
    setBusy(true);
    try {
      const updated = await api.action(subscription.id, action, {
        as_of: asOf,
        ...(action === "quotation" ? { validity_days: Number(validity) } : {}),
        ...(action === "renew" ? { new_expiry_date: expiry } : {}),
      });
      onSuccess(updated);
    } catch (cause) {
      setError(
        cause instanceof Error
          ? cause.message
          : "The action failed. Please try again.",
      );
    } finally {
      setBusy(false);
    }
  }
  return (
    <Modal title={actionLabels[action]} onClose={onClose} busy={busy}>
      <form onSubmit={submit}>
        <div className="modal-body">
          <span className="pill self-start">{subscription.number}</span>
          <p>{explanations[action]}</p>
          {error && <Notice>{error}</Notice>}
          <label className="field">
            Business date (as of)
            <input
              aria-label="Business date (as of)"
              type="date"
              value={asOf}
              onChange={(event) => setAsOf(event.target.value)}
              required
            />
          </label>
          {action === "quotation" && (
            <label className="field">
              Quotation validity (days)
              <input
                aria-label="Quotation validity (days)"
                type="number"
                min={1}
                max={3650}
                step={1}
                value={validity}
                onChange={(event) => setValidity(event.target.value)}
                required
              />
            </label>
          )}
          {action === "renew" && (
            <label className="field">
              New expiry date
              <input
                aria-label="New expiry date"
                type="date"
                value={expiry}
                onChange={(event) => setExpiry(event.target.value)}
                required
              />
            </label>
          )}
        </div>
        <div className="modal-footer">
          <Button type="button" onClick={onClose} disabled={busy}>
            Cancel
          </Button>
          <Button
            type="submit"
            variant={action === "close" ? "danger" : "primary"}
            disabled={busy}
          >
            {busy ? "Saving…" : actionLabels[action]}
          </Button>
        </div>
      </form>
    </Modal>
  );
}
